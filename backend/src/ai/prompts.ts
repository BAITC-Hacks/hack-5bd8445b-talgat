export function analyzeUserMessage(input: { rawDraft: string; topic: string; businessName: string }): string {
  return `Отрасль: ${input.topic}
Компания: ${input.businessName}
Черновик:
"""
${input.rawDraft}
"""`;
}

export function structureUserMessage(input: {
  rawDraft: string;
  topic: string;
  fields: CardFields;
  qa: Array<{ field: string; question: string; answer: string }>;
}): string {
  const qa = input.qa
    .map((x, i) => `${i + 1}. [поле: ${x.field}] ${x.question}\nОтвет: ${x.answer.trim() || '(нет ответа)'}`)
    .join('\n');
  return `Отрасль: ${input.topic}
Черновик:
"""
${input.rawDraft}
"""
Текущие поля карточки (JSON):
${JSON.stringify(input.fields, null, 2)}
Вопросы и ответы:
${qa}`;
}

/** Повторный запрос, если ответ модели не прошёл проверку схемы */
export function repairMessage(error: string): string {
  return `Предыдущий ответ не прошёл проверку: ${error}. Верни исправленный ответ строго по JSON-схеме, без пояснений.`;
}
